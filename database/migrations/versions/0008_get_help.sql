-- =============================================================================
-- A resident asks for help (see 0008_get_help.py).
--
--   * Safe contact: how the person wants to be reached (call, text, not at
--     all) and whether it's safe to call or leave a voicemail. Workers only,
--     like the other contact columns.
--   * Requests without an account: an emergency shouldn't wait on a sign-in.
--     Such a request has no requester_id; whoever holds its number and its
--     access code can read it and reply. Only the code's SHA-256 is stored.
--   * Replies: the requester can answer on their request (update_type
--     'reply', always public).
--   * Tasks: the work a case needs, generated by the API when the case comes
--     in (services/tasks.py) and closed by workers.
--
-- Same conventions as 0003 and 0005: app.<domain>_<verb>, p_ parameters, no
-- row means not found, SECURITY INVOKER.
-- =============================================================================

-- =============================================================================
-- CASES: safe contact and access codes
-- =============================================================================

ALTER TABLE app.cases
    -- NULL: not asked (cases workers open).
    ADD COLUMN contact_method TEXT
        CONSTRAINT cases_contact_method_check CHECK (contact_method IN ('call', 'text', 'none')),
    -- "It's safe to call or leave a voicemail" (or to text). NULL: not asked.
    ADD COLUMN safe_to_contact BOOLEAN,
    -- SHA-256 of the access code of a request sent without an account.
    ADD COLUMN access_code_hash BYTEA
        CONSTRAINT cases_access_code_hash_check CHECK (octet_length(access_code_hash) = 32);

-- Columns may only be added at the end of a view.
CREATE OR REPLACE VIEW app.case_view AS
SELECT c.id, c.number, c.kind, c.title, c.description, c.category, c.priority, c.status, c.source,
       c.location, c.latitude, c.longitude, c.contact_name, c.contact_phone, c.contact_email,
       c.requester_id, c.assigned_worker_id, w.display_name AS assigned_worker_name,
       c.created_by, c.created_at, c.updated_at, c.resolved_at,
       (SELECT count(*) FROM app.case_referrals r WHERE r.case_id = c.id) AS referral_count,
       COALESCE((SELECT max(u.created_at) FROM app.case_updates u WHERE u.case_id = c.id), c.created_at)
           AS last_activity_at,
       c.contact_method, c.safe_to_contact
FROM app.cases c
LEFT JOIN app.users w ON w.id = c.assigned_worker_id;

-- A requester's answer on their own request.
ALTER TABLE app.case_updates DROP CONSTRAINT case_updates_type_check;
ALTER TABLE app.case_updates ADD CONSTRAINT case_updates_type_check CHECK (update_type IN (
    'created', 'note', 'message', 'status_change', 'priority_change',
    'category_change', 'assignment', 'referral', 'reply'));

-- =============================================================================
-- TASKS
-- =============================================================================

CREATE TABLE app.tasks (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    case_id            UUID NOT NULL REFERENCES app.cases (id) ON DELETE CASCADE,
    title              TEXT NOT NULL CONSTRAINT tasks_title_check CHECK (length(title) BETWEEN 1 AND 160),
    detail             TEXT NOT NULL DEFAULT '' CONSTRAINT tasks_detail_check CHECK (length(detail) <= 2000),
    status             TEXT NOT NULL DEFAULT 'open' CONSTRAINT tasks_status_check CHECK (status IN ('open', 'done')),
    -- NULL: whoever holds the case.
    assigned_worker_id UUID REFERENCES app.users (id) ON DELETE SET NULL,
    due_at             TIMESTAMPTZ,
    -- NULL: generated by the system.
    created_by         UUID REFERENCES app.users (id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    completed_at       TIMESTAMPTZ,
    completed_by       UUID REFERENCES app.users (id) ON DELETE SET NULL
);

CREATE INDEX tasks_case_idx ON app.tasks (case_id, created_at);
CREATE INDEX tasks_open_due_idx ON app.tasks (due_at) WHERE status = 'open';

-- assigned_worker_id is the task's own assignee, or the case's when the task
-- has none: a task follows its case until someone hands it to another person.
CREATE VIEW app.task_view AS
SELECT t.id, t.case_id, c.number AS case_number, c.title AS case_title, c.category AS case_category,
       c.priority AS case_priority, t.title, t.detail, t.status,
       COALESCE(t.assigned_worker_id, c.assigned_worker_id) AS assigned_worker_id,
       w.display_name AS assigned_worker_name,
       t.due_at, t.created_by, t.created_at, t.completed_at, t.completed_by
FROM app.tasks t
JOIN app.cases c ON c.id = t.case_id
LEFT JOIN app.users w ON w.id = COALESCE(t.assigned_worker_id, c.assigned_worker_id);

-- =============================================================================
-- REQUEST FUNCTIONS (the person asking for help)
-- =============================================================================

-- A request from a resident: signed in (p_requester_id) or not (then
-- p_access_code_hash is how they get back to it). Writes the public
-- "Request received." entry, as case_create does.
CREATE FUNCTION app.request_create(
    p_title TEXT, p_description TEXT, p_category TEXT, p_priority TEXT,
    p_location TEXT, p_latitude DOUBLE PRECISION, p_longitude DOUBLE PRECISION,
    p_contact_name TEXT, p_contact_phone TEXT, p_contact_email TEXT,
    p_contact_method TEXT, p_safe_to_contact BOOLEAN,
    p_requester_id UUID, p_access_code_hash BYTEA)
RETURNS SETOF app.case_view
LANGUAGE plpgsql AS $$
DECLARE
    v_id UUID;
BEGIN
    IF (p_requester_id IS NULL) = (p_access_code_hash IS NULL) THEN
        RAISE EXCEPTION 'A request has a requester or an access code, not both or neither'
            USING ERRCODE = 'check_violation';
    END IF;

    INSERT INTO app.cases AS c (kind, title, description, category, priority, status, source, location,
                                latitude, longitude, contact_name, contact_phone, contact_email,
                                contact_method, safe_to_contact, requester_id, access_code_hash, created_by)
    VALUES ('request', p_title, p_description, p_category, p_priority, 'new', 'public', p_location,
            p_latitude, p_longitude, p_contact_name, p_contact_phone, p_contact_email,
            p_contact_method, p_safe_to_contact, p_requester_id, p_access_code_hash, p_requester_id)
    RETURNING c.id INTO v_id;

    INSERT INTO app.case_updates (case_id, author_id, update_type, visibility, content)
    VALUES (v_id, p_requester_id, 'created', 'public', 'Request received.');

    RETURN QUERY SELECT * FROM app.case_view v WHERE v.id = v_id;
END
$$;

-- A request sent without an account, by its number and access code. The
-- same public columns as request_get_for_user.
CREATE FUNCTION app.request_get_by_code(p_number BIGINT, p_access_code_hash BYTEA)
RETURNS TABLE (id UUID, number BIGINT, title TEXT, description TEXT, category TEXT, status TEXT,
               location TEXT, created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ, resolved_at TIMESTAMPTZ)
LANGUAGE sql STABLE AS $$
    SELECT c.id, c.number, c.title, c.description, c.category, c.status, c.location,
           c.created_at, c.updated_at, c.resolved_at
    FROM app.cases c
    WHERE c.number = p_number AND c.access_code_hash = p_access_code_hash
$$;

-- Public updates on one request, for a caller the API has already matched
-- to it (by account or by access code). Who wrote them stays internal.
CREATE FUNCTION app.request_list_public_updates(p_case_id UUID)
RETURNS TABLE (id UUID, update_type TEXT, content TEXT, created_at TIMESTAMPTZ)
LANGUAGE sql STABLE AS $$
    SELECT u.id, u.update_type, u.content, u.created_at
    FROM app.case_updates u
    WHERE u.case_id = p_case_id AND u.visibility = 'public'
    ORDER BY u.created_at, u.id
$$;

-- The requester answers on their request. No row when the case doesn't exist.
CREATE FUNCTION app.request_add_reply(p_case_id UUID, p_author_id UUID, p_content TEXT)
RETURNS TABLE (id UUID, update_type TEXT, content TEXT, created_at TIMESTAMPTZ)
LANGUAGE plpgsql AS $$
DECLARE
    v_id UUID;
BEGIN
    UPDATE app.cases AS c SET updated_at = now() WHERE c.id = p_case_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    INSERT INTO app.case_updates AS u (case_id, author_id, update_type, visibility, content)
    VALUES (p_case_id, p_author_id, 'reply', 'public', p_content)
    RETURNING u.id INTO v_id;
    RETURN QUERY SELECT u.id, u.update_type, u.content, u.created_at FROM app.case_updates u WHERE u.id = v_id;
END
$$;

-- =============================================================================
-- TASK FUNCTIONS (workers)
-- =============================================================================

-- No row when the case doesn't exist.
CREATE FUNCTION app.task_create(
    p_case_id UUID, p_title TEXT, p_detail TEXT, p_due_at TIMESTAMPTZ, p_assigned_worker_id UUID,
    p_created_by UUID)
RETURNS SETOF app.task_view
LANGUAGE plpgsql AS $$
DECLARE
    v_id UUID;
BEGIN
    PERFORM 1 FROM app.cases c WHERE c.id = p_case_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    INSERT INTO app.tasks AS t (case_id, title, detail, due_at, assigned_worker_id, created_by)
    VALUES (p_case_id, p_title, COALESCE(p_detail, ''), p_due_at, p_assigned_worker_id, p_created_by)
    RETURNING t.id INTO v_id;
    RETURN QUERY SELECT * FROM app.task_view v WHERE v.id = v_id;
END
$$;

-- Filters are ANDed; NULL means "any". p_assigned_worker_id matches the
-- effective assignee (the task's, else the case's). Open tasks first, by due
-- time (none last), then oldest.
CREATE FUNCTION app.task_list(p_case_id UUID, p_assigned_worker_id UUID, p_open_only BOOLEAN, p_limit INTEGER)
RETURNS SETOF app.task_view
LANGUAGE sql STABLE AS $$
    SELECT v.*
    FROM app.task_view v
    WHERE (p_case_id IS NULL OR v.case_id = p_case_id)
      AND (p_assigned_worker_id IS NULL OR v.assigned_worker_id = p_assigned_worker_id)
      AND (NOT COALESCE(p_open_only, false) OR v.status = 'open')
    ORDER BY (v.status = 'done'), v.due_at NULLS LAST, v.created_at, v.id
    LIMIT COALESCE(p_limit, 200)
$$;

CREATE FUNCTION app.task_get(p_task_id UUID)
RETURNS SETOF app.task_view
LANGUAGE sql STABLE AS $$
    SELECT v.* FROM app.task_view v WHERE v.id = p_task_id
$$;

-- NULL leaves a field as it is; p_unassign hands the task back to whoever
-- holds the case. Finishing or reopening a task is written to the case's
-- (internal) history by p_actor_id. No row when the task doesn't exist.
CREATE FUNCTION app.task_update(
    p_task_id UUID, p_actor_id UUID, p_status TEXT, p_assigned_worker_id UUID, p_unassign BOOLEAN)
RETURNS SETOF app.task_view
LANGUAGE plpgsql AS $$
DECLARE
    v_old app.tasks%ROWTYPE;
    v_new app.tasks%ROWTYPE;
BEGIN
    SELECT * INTO v_old FROM app.tasks t WHERE t.id = p_task_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    UPDATE app.tasks AS t
    SET status = COALESCE(p_status, t.status),
        assigned_worker_id = CASE WHEN COALESCE(p_unassign, false) THEN NULL
                                  ELSE COALESCE(p_assigned_worker_id, t.assigned_worker_id) END,
        completed_at = CASE WHEN COALESCE(p_status, t.status) = 'done' THEN COALESCE(t.completed_at, now())
                            ELSE NULL END,
        completed_by = CASE WHEN COALESCE(p_status, t.status) = 'done' THEN COALESCE(t.completed_by, p_actor_id)
                            ELSE NULL END
    WHERE t.id = p_task_id
    RETURNING t.* INTO v_new;

    IF v_new.status IS DISTINCT FROM v_old.status THEN
        UPDATE app.cases AS c SET updated_at = now() WHERE c.id = v_new.case_id;
        INSERT INTO app.case_updates (case_id, author_id, update_type, content)
        VALUES (v_new.case_id, p_actor_id, 'note',
                CASE WHEN v_new.status = 'done' THEN 'Task done: ' ELSE 'Task reopened: ' END
                || v_new.title);
    END IF;

    RETURN QUERY SELECT * FROM app.task_view v WHERE v.id = p_task_id;
END
$$;
